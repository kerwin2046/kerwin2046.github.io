// 滑动窗口通过两个指针维护一个区间，右指针单调递增用于扩展窗口，左指针在窗口不满足条件时单调递增用于收缩窗口。
// 由于两个指针都只向右移动，每个元素最多被访问两次，因此整体时间复杂度为 O(n)。
/**
 * 1.初始化
 *   将左指针和右指针都初始化为数组的起始位置。left = 0, right = 0
 *
 * 2.扩展右边界,right++,把新元素加入窗口,同时更新窗口状态
 *     如果窗口满足条件（比如窗口内的元素数量、窗口内的元素和等于目标值等），就继续扩展右边界；
 *     如果窗口不满足条件，就进入下一步调整左边界的阶段
 *
 * 3.根据问题条件（比如窗口里的元素超过限制、不满足目标），循环移动左指针（left++），直到窗口重新满足条件；
 *
 * 4.每次调整窗口后，看看当前窗口是不是更优解（比如长度更大、更小之类的），然后记录下来。

 */
// 滑动窗口的核心在于动态调整窗口的大小和位置，以满足特定的条件。通过不断扩展右边界和收缩左边界，滑动窗口能够高效地找到满足条件的子集，从而避免了暴力解法中重复计算的问题。这种技巧在处理字符串、数组等线性数据结构中的子集问题时非常有用，可以显著降低时间复杂度。
// 滑动窗口的应用场景非常广泛，常见的包括：
// 1.寻找满足条件的最长子串或子数组（如最长无重复字符的子串）
// 2.计算满足条件的子串或子数组的数量（如包含所有字符的最小窗口）
// 3.动态维护一个窗口内的数据状态（如滑动窗口最大值）
// 4.处理连续子集问题（如连续子数组和等于目标值）
// 5.优化暴力解法，避免重复计算（如字符串匹配问题）
// 案例1:固定窗口大小,比如寻找长度为k的子数组的最大和
function maxSumSubarray(arr, k) {
    var left = 0;
    var right = 0;
    var maxSum = 0;
    var currentSum = 0;
    while (right < arr.length) {
        currentSum += arr[right];
        if (right - left + 1 > k) { // 窗口大小超过k了，收缩窗口
            currentSum -= arr[left];
            left++;
        }
        if (right - left + 1 === k) { // 窗口大小正好是k了，更新最大和
            maxSum = Math.max(maxSum, currentSum);
        }
        right++;
    }
    return maxSum;
}
